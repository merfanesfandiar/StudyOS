/**
 * Message catalogue.
 *
 * `en` is the source of truth and its keys define `MessageKey`. Every other
 * locale is typed as `Record<MessageKey, string>`, so omitting a key is a
 * compile error rather than an English string leaking into a Persian page at
 * runtime. That inversion is deliberate: the compiler, not a reviewer, is what
 * catches an untranslated string.
 *
 * Placeholders use `{name}` and are substituted by `translate`. They are
 * positional by name, not by order, so a translator can move a fragment within a
 * sentence — which they must be able to do, since Persian word order is not
 * English word order.
 */

